export default function ReviewingComplexInformation() {
  return (
    <main>
      <h1>How to Gain the Ability to Review Complex Information from Multiple Sources and Determine Relevant Information to a Given Situation</h1>

      <section>
        <h2>Clarify the Situation and Question</h2>
        <p>
          Before reviewing sources, define what you need to know. What decision must be made? What problem are you solving? What audience or context matters? A clear question focuses your review and helps you recognize relevant information when you see it.
        </p>
      </section>

      <section>
        <h2>Establish Criteria for Relevance</h2>
        <p>
          Decide what makes information relevant: Does it address the question directly? Is it from a credible, current source? Does it apply to your audience, product, or jurisdiction? Criteria help you filter quickly instead of reading everything equally.
        </p>
      </section>

      <section>
        <h2>Scan and Triage Before Deep Reading</h2>
        <p>
          Use headings, summaries, and tables of contents to scan sources first. Mark what appears relevant; skip or skim the rest. Triaging reduces overload and directs effort to material that matters. Revisit triage criteria if you discover the question has changed.
        </p>
      </section>

      <section>
        <h2>Synthesize Across Sources</h2>
        <p>
          Look for agreements, conflicts, and gaps across sources. Note which sources support which conclusions and where they diverge. Synthesizing reveals patterns and helps you weigh evidence rather than treating each source in isolation.
        </p>
      </section>

      <section>
        <h2>Connect to the Situation</h2>
        <p>
          Relate what you found to the specific situation. Does a guideline apply to your product? Does a standard cover your use case? Translating general information into situational relevance is the step that turns research into action.
        </p>
      </section>

      <section>
        <h2>Document and Communicate What Matters</h2>
        <p>
          Record which information you deemed relevant and why. Cite sources and note limitations (e.g., outdated, not applicable to your context). Clear documentation helps others understand your reasoning and supports future decisions.
        </p>
      </section>
    </main>
  );
}
